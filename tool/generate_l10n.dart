/// Generates compiled, dependency-free translations from the ARB catalogs.
/// Usage: dart run tool/generate_l10n.dart [--check]
library;

import 'dart:convert';
import 'dart:io';

final _identifier = RegExp(r'^[a-zA-Z][a-zA-Z0-9]*$');
final _placeholder = RegExp(r'\{([a-zA-Z][a-zA-Z0-9]*)\}');

String _literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');

String generate(Map<String, dynamic> en, Map<String, dynamic> ar) {
  final keys = en.keys.where((k) => !k.startsWith('@')).toList()..sort();
  final other = ar.keys.where((k) => !k.startsWith('@')).toSet();
  if (en['@@locale'] != 'en' ||
      ar['@@locale'] != 'ar' ||
      other.length != keys.length ||
      !other.containsAll(keys)) {
    throw const FormatException('ARB locales and translation keys must match.');
  }
  final parameters = <String, List<String>>{};
  for (final key in keys) {
    if (!_identifier.hasMatch(key)) throw FormatException('Invalid key: $key');
    final metadata = en['@$key'];
    if (metadata is! Map || metadata['description'] is! String) {
      throw FormatException('Missing description for $key');
    }
    final declared =
        (metadata['placeholders'] as Map?)?.keys.cast<String>().toSet() ??
            <String>{};
    for (final catalog in [en, ar]) {
      final value = catalog[key];
      if (value is! String || value.isEmpty) {
        throw FormatException('Empty translation: $key');
      }
      final used = _placeholder.allMatches(value).map((m) => m[1]!).toSet();
      if (used.length != declared.length || !used.containsAll(declared)) {
        throw FormatException('Placeholder mismatch for $key');
      }
      // Fail loudly instead of silently misrendering unsupported ICU syntax.
      if (value.replaceAll(_placeholder, '').contains(RegExp(r'[{}]'))) {
        throw FormatException('Unsupported ICU/literal braces in $key');
      }
    }
    parameters[key] = declared.toList()..sort();
  }
  final out = StringBuffer(
      '// GENERATED by tool/generate_l10n.dart. Edit app_en.arb / app_ar.arb.\n'
      '// ignore_for_file: lines_longer_than_80_chars, prefer_interpolation_to_compose_strings\n\n');
  String args(String key) => parameters[key]!.map((p) => '$p: $p').join(', ');
  String signature(String key) => parameters[key]!.isEmpty
      ? 'String get $key'
      : 'String $key({${parameters[key]!.map((p) => 'required Object? $p').join(', ')}})';
  out.writeln(
      'class L10n {\n  const L10n(this.locale);\n  final String locale;\n  bool get isArabic => locale.toLowerCase().split(RegExp(r"[-_]"))[0] == "ar";');
  for (final key in keys) {
    final suffix = parameters[key]!.isEmpty ? '' : '(${args(key)})';
    out.writeln(
        '  ${signature(key)} => isArabic ? Ar.$key$suffix : En.$key$suffix;');
  }
  out.writeln('}\n');
  for (final locale in [('En', en), ('Ar', ar)]) {
    out.writeln('abstract final class ${locale.$1} {');
    for (final key in keys) {
      final value = locale.$2[key] as String;
      if (parameters[key]!.isEmpty) {
        out.writeln('  static const $key = ${_literal(value)};');
      } else {
        // Compile interpolation, rather than repeated replacements that could
        // accidentally interpret a placeholder contained in an argument value.
        final chunks = <String>[];
        var start = 0;
        for (final match in _placeholder.allMatches(value)) {
          chunks.add(_literal(value.substring(start, match.start)));
          chunks.add('${match[1]}.toString()');
          start = match.end;
        }
        chunks.add(_literal(value.substring(start)));
        out.writeln('  static ${signature(key)} => ${chunks.join(' + ')};');
      }
    }
    out.writeln('}\n');
  }
  return out.toString();
}

/// [source] without the whitespace between tokens. The generated file is kept
/// formatted, and the formatter only moves whitespace outside string literals,
/// so a formatted file and fresh generator output compare equal through this.
String significant(String source) {
  final out = StringBuffer();
  var inString = false;
  for (var i = 0; i < source.length; i++) {
    final char = source[i];
    if (inString) {
      out.write(char);
      if (char == r'\' && i + 1 < source.length) {
        out.write(source[++i]);
      } else if (char == '"') {
        inString = false;
      }
    } else if (char == '"') {
      inString = true;
      out.write(char);
    } else if (char.trim().isNotEmpty) {
      out.write(char);
    }
  }
  return out.toString();
}

void main(List<String> args) {
  try {
    if (args.any((a) => a != '--check')) {
      throw const FormatException('Use --check or no arguments.');
    }
    final root = File.fromUri(Platform.script).parent.parent;
    final folder = Directory('${root.path}/lib/src/l10n');
    final result = generate(
        jsonDecode(File('${folder.path}/app_en.arb').readAsStringSync())
            as Map<String, dynamic>,
        jsonDecode(File('${folder.path}/app_ar.arb').readAsStringSync())
            as Map<String, dynamic>);
    final output = File('${folder.path}/messages.g.dart');
    if (args.contains('--check')) {
      if (!output.existsSync() ||
          significant(output.readAsStringSync()) != significant(result)) {
        throw const FormatException(
            'Generated translations are stale. Run dart run tool/generate_l10n.dart.');
      }
      stdout
          .writeln('ARB catalogs and generated translations are synchronized.');
    } else {
      output.writeAsStringSync(result);
      // Keep the generated file formatted like the rest of the package.
      final formatted =
          Process.runSync(Platform.resolvedExecutable, ['format', output.path]);
      if (formatted.exitCode != 0) {
        throw FormatException(
            'Could not format ${output.path}: ${formatted.stderr}');
      }
      stdout.writeln('Generated ${output.path}');
    }
  } on FormatException catch (e) {
    stderr.writeln(e.message);
    exitCode = 1;
  }
}
